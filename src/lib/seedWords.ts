export async function seedElementaryWords(): Promise<number> {
  const { listWords, addWordsBulk } = await import("./words");
  const existing = await listWords();
  const existingTerms = new Set(existing.map((w) => w.term.toLowerCase()));
  const seen = new Set<string>();
  const toAdd: { term: string; meaning: string; example?: string }[] = [];
  for (const w of ELEMENTARY_WORDS) {
    const key = w.term.toLowerCase();
    if (existingTerms.has(key) || seen.has(key)) continue;
    seen.add(key);
    toAdd.push({ term: w.term, meaning: w.meaning, example: w.example });
  }
  if (toAdd.length === 0) return 0;
  await addWordsBulk(toAdd);
  return toAdd.length;
}
